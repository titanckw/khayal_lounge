function icon($name, $class = '')
{
    $class = trim('icon ' . $class);
    return '<svg class="' . htmlspecialchars($class) . '" aria-hidden="true" focusable="false"><use href="#i-' . htmlspecialchars($name) . '"/></svg>';
}

/** Five stars, the first $rating filled in. */
function star_rating($rating, $class = '')
{
    $rating = max(0, min(5, (int) $rating));
    $out = '<span class="star-rating ' . htmlspecialchars($class) . '" role="img" aria-label="' . $rating . ' out of 5 stars">';
    for ($i = 1; $i <= 5; $i++) {
        $out .= icon('star', $i <= $rating ? 'is-filled' : 'is-empty');
    }
    return $out . '</span>';
}
